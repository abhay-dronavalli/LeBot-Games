"""Writes roblox/tools/install_obby_mode.lua from the repo's Robo Obby files.

Run from anywhere:  python roblox/tools/build_install_obby.py
Re-run it after changing any file in FILES, then run the output in Studio (command bar or the
Studio MCP's execute_luau) in the arcade place. The output embeds every file's source, so it is the
one step that imports the mode's code into the arcade. The map is separate (it is geometry, not code):
roblox/tools/prepare_obby_map.lua packs it out of lebot_obby/Place1.rbxl, and you insert the exported
places/ObbyMap.rbxm as ServerStorage.Modes.Obby.Map (docs/obby-mode-plan.md "Getting the map in").
"""

from pathlib import Path

ROBLOX = Path(__file__).resolve().parent.parent
OUT = ROBLOX / "tools" / "install_obby_mode.lua"

SERVER = [
    "RunControl", "BlockSync", "SkyArm", "ArmMirror", "HazardManager", "ActiveBayTracker", "BridgeFeed",
    "DebugMode", "Status", "DebugMenu", "GhostMode", "BayData", "CrateDefs", "Mapping",
]
PLAYER_TEMPLATES = ["ObjectiveHud", "CellEditor", "BackdropFx", "CameraPolish", "DarkRoom"]
DEBUG_TEMPLATES = ["DebugMenu", "GhostControl"]

# (Studio path, class, repo file). Parents are created as Folders when missing. ServerStorage.Modes.Obby
# is NOT replaced as a whole (it holds the Map): only its Module and its Server folder are.
# ReplicatedStorage.Obby is replaced as a whole.
FILES = (
    [("ServerStorage.Modes.Obby.Module", "ModuleScript", "ServerStorage/Modes/Obby/Module.lua")]
    + [("ServerStorage.Modes.Obby.Server." + n, "ModuleScript", "ServerStorage/Modes/Obby/Server/%s.lua" % n)
       for n in SERVER]
    + [("ReplicatedStorage.Obby.Config", "ModuleScript", "ReplicatedStorage/Obby/Config.lua"),
       ("ReplicatedStorage.Obby.UiTheme", "ModuleScript", "ReplicatedStorage/Obby/UiTheme.lua"),
       ("ReplicatedStorage.Obby.Views.PlayerView", "ModuleScript", "ReplicatedStorage/Obby/Views/PlayerView.lua"),
       ("ReplicatedStorage.Obby.Views.RobotView", "ModuleScript", "ReplicatedStorage/Obby/Views/RobotView.lua")]
    + [("ReplicatedStorage.Obby.Views.Player." + n, "LocalScript",
        "ReplicatedStorage/Obby/Views/Player/%s.client.lua" % n) for n in PLAYER_TEMPLATES]
    + [("ReplicatedStorage.Obby.Views.Debug." + n, "LocalScript",
        "ReplicatedStorage/Obby/Views/Debug/%s.client.lua" % n) for n in DEBUG_TEMPLATES]
    + [("ReplicatedStorage.Core.Games.Obby", "ModuleScript", "ReplicatedStorage/Core/Games/Obby.lua")]
)

REMOTES = ["Objective", "CellEdit", "CellsUpdated", "DebugHotkey", "GhostToggle", "DebugCommand", "Status",
           "BayCells", "CameraFace", "Toast"]

HEADER = """-- roblox/tools/install_obby_mode.lua  (GENERATED by roblox/tools/build_install_obby.py - do not edit;
-- change the repo files and re-run the generator)
-- Imports Robo Obby's code into the arcade place in one step (docs/obby-mode-plan.md). Run it in Studio, in
-- Edit mode: paste it into the command bar, or the Studio MCP's execute_luau. It creates:
--   ServerStorage.Modes.Obby.Module    (ModuleScript)  the arcade mode                 [replaced if present]
--   ServerStorage.Modes.Obby.Server    (Folder)  the course's server modules, cloned per round  [replaced]
--   ReplicatedStorage.Obby             (Folder)  Config, UiTheme, Remotes (the RemoteEvents), Views.*  [replaced]
--   ReplicatedStorage.Core.Games.Obby  (ModuleScript)  the GameRegistry entry           [replaced if present]
-- It keeps ServerStorage.Modes.Obby.Map (insert places/ObbyMap.rbxm there, made by
-- roblox/tools/prepare_obby_map.lua in Place1) and checks it: Warehouse / Backdrop / Start / Finish /
-- LobbyPad, no SpawnLocation or script inside, Persistent streaming, moved to Config.OriginZ. It disables
-- (never deletes) standalone obby scripts left over from Place1, which would open their own robot socket,
-- set Lighting and run outside the mode contract. It touches nothing else (not Lighting, not the Workshop);
-- the bay Workspace.Workshop.Bays.Bay1_Obby already names this mode ("Obby").

local ServerStorage = game:GetService("ServerStorage")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local StarterPlayer = game:GetService("StarterPlayer")
local CollectionService = game:GetService("CollectionService")
local ChangeHistoryService = game:GetService("ChangeHistoryService")

local SERVICES = { ServerStorage = ServerStorage, ReplicatedStorage = ReplicatedStorage }
local made = {}
local problems = {}

local function problem(fmt, ...)
	table.insert(problems, string.format(fmt, ...))
end

local function folderAt(path)
	local names = string.split(path, ".")
	local node = SERVICES[names[1]]
	assert(node, "unknown service in " .. path)
	for i = 2, #names do
		local child = node:FindFirstChild(names[i])
		if not child then
			child = Instance.new("Folder")
			child.Name = names[i]
			child.Parent = node
		end
		node = child
	end
	return node
end

local function put(path, className, source)
	local parentPath, name = string.match(path, "^(.*)%.([^%.]+)$")
	local parent = folderAt(parentPath)
	local old = parent:FindFirstChild(name)
	if old then
		old:Destroy()
	end
	local inst = Instance.new(className)
	inst.Name = name
	inst.Source = source
	inst.Parent = parent
	table.insert(made, path)
	return inst
end

local function replace(path)
	local parentPath, name = string.match(path, "^(.*)%.([^%.]+)$")
	local parent = folderAt(parentPath)
	local old = parent:FindFirstChild(name)
	if old then
		print("[install_obby_mode] replacing " .. old:GetFullName())
		old:Destroy()
	end
end

pcall(function()
	ChangeHistoryService:SetWaypoint("Before installing Robo Obby")
end)

assert(ReplicatedStorage:FindFirstChild("Core") and ReplicatedStorage.Core:FindFirstChild("GameRegistry"),
	"ReplicatedStorage.Core (the roles core) is missing: install the arcade lobby first")
if not (ServerStorage:FindFirstChild("Shared") and ServerStorage.Shared:FindFirstChild("StateStore")
	and ServerStorage.Shared:FindFirstChild("Bridge")) then
	problem("ServerStorage.Shared.StateStore / Bridge are missing: every round runs solo (no robot)")
end
if not ServerScriptService:FindFirstChild("Bridge") then
	problem("ServerScriptService.Bridge (the core's robot link) is missing: every round runs solo")
end

replace("ServerStorage.Modes.Obby.Server")
replace("ServerStorage.Modes.Obby.Runtime") -- a round's clone saved by accident; Start makes a fresh one
replace("ReplicatedStorage.Obby")

local SOURCES = {}
"""

FOOTER = """
for _, entry in ipairs(SOURCES) do
	put(entry.path, entry.class, entry.source)
end

-- The remotes Module would make when it first loads, made now so the tree is complete in Edit mode.
local remotes = folderAt("ReplicatedStorage.Obby.Remotes")
for _, name in ipairs(REMOTES) do
	local r = Instance.new("RemoteEvent")
	r.Name = name
	r.Parent = remotes
end

-- The standalone place's scripts, if someone pasted them in: off, so they cannot open a second robot
-- socket, set Lighting or run the course outside the mode.
local starterScripts = StarterPlayer:FindFirstChild("StarterPlayerScripts")
for _, pair in ipairs({
	{ ServerScriptService, { "HazardManager", "BridgeFeed", "DebugMode", "DebugMenu", "GhostMode", "ActiveBayTracker" } },
	{ starterScripts, { "OverseerCam", "ObjectiveHud", "DebugCellEditor", "DebugMenu", "GhostControl", "BackdropFx",
		"CameraPolish" } },
}) do
	local parent, names = pair[1], pair[2]
	for _, name in ipairs(parent and names or {}) do
		local old = parent:FindFirstChild(name)
		if old and old:IsA("BaseScript") then
			old.Enabled = false
			problem("disabled the standalone %s; delete it when you are sure", old:GetFullName())
		end
	end
end
for _, name in ipairs({ "RunControl", "BlockSync", "SkyArm", "ArmMirror" }) do
	if ServerScriptService:FindFirstChild(name) then
		problem("ServerScriptService.%s (a standalone obby module?) is still there; the mode never uses it", name)
	end
end
for _, name in ipairs({ "Config", "BayData", "CrateDefs", "Mapping", "UiTheme" }) do
	if ReplicatedStorage:FindFirstChild(name) then
		problem("ReplicatedStorage.%s exists: if it is the standalone obby's, it is unused now", name)
	end
end

-- The map: geometry from Place1, inserted by hand (places/ObbyMap.rbxm).
local Config = require(ReplicatedStorage.Obby.Config)
local mode = ServerStorage.Modes.Obby
local map = mode:FindFirstChild("Map")
if not map then
	problem("ServerStorage.Modes.Obby.Map is missing: insert places/ObbyMap.rbxm (docs/obby-mode-plan.md \\"Getting the map in\\")")
elseif not map:IsA("Model") then
	problem("ServerStorage.Modes.Obby.Map is a %s, not a Model", map.ClassName)
else
	if map.ModelStreamingMode ~= Enum.ModelStreamingMode.Persistent then
		map.ModelStreamingMode = Enum.ModelStreamingMode.Persistent
		print("[install_obby_mode] set Map.ModelStreamingMode = Persistent")
	end
	for _, name in ipairs({ "Warehouse", "Backdrop", "Start", "Finish", "LobbyPad" }) do
		if not map:FindFirstChild(name) then
			problem("Map.%s is missing", name)
		end
	end
	local pad = map:FindFirstChild("LobbyPad")
	if pad and not CollectionService:HasTag(pad, "LobbyTeleporter") then
		CollectionService:AddTag(pad, "LobbyTeleporter")
		print("[install_obby_mode] tagged Map.LobbyPad LobbyTeleporter")
	end
	for _, d in ipairs(map:GetDescendants()) do
		if d:IsA("SpawnLocation") then
			problem("%s is a SpawnLocation: arcade players could spawn into the obby", d:GetFullName())
		elseif d:IsA("BaseScript") then
			problem("%s is a script inside the map; maps hold no code", d:GetFullName())
		end
	end
	local warehouse = map:FindFirstChild("Warehouse")
	local bay1 = warehouse and warehouse:FindFirstChild("Bay01")
	local anchors = bay1 and bay1:FindFirstChild("CrateAnchors")
	local anchor = anchors and anchors:FindFirstChild("Cell_0_0")
	local expected = Config.OriginZ + Config.CellSize / 2
	if anchor and math.abs(anchor.Position.Z - expected) > 1 then
		problem("Bay01.CrateAnchors.Cell_0_0 is at Z %.1f; expected about %.1f (Config.OriginZ %d). Map not moved?",
			anchor.Position.Z, expected, Config.OriginZ)
	end
end

local workshop = workspace:FindFirstChild("Workshop")
local bays = workshop and workshop:FindFirstChild("Bays")
local cabinet = nil
for _, bay in ipairs(bays and bays:GetChildren() or {}) do
	if (bay:GetAttribute("Mode") or bay.Name) == "Obby" then
		cabinet = bay
	end
end
if not cabinet then
	problem("no Workspace.Workshop.Bays.* with Mode = \\"Obby\\": the arcade has no portal for it")
end

pcall(function()
	ChangeHistoryService:SetWaypoint("Installed Robo Obby")
end)
print(string.format("[install_obby_mode] installed %d scripts and %d remotes%s", #made, #REMOTES,
	cabinet and (" for " .. cabinet:GetFullName()) or ""))
for _, line in ipairs(problems) do
	warn("[install_obby_mode] " .. line)
end
"""


def long_string(text: str) -> str:
    level = 1
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    # Lua drops the newline right after the opening bracket, so the source starts on its first line.
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def repr_lua(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    parts = [HEADER]
    for path, cls, rel in FILES:
        src = (ROBLOX / rel).read_text(encoding="utf-8").replace("\r\n", "\n")
        parts.append(
            "table.insert(SOURCES, { path = %s, class = %s, source = %s })\n"
            % (repr_lua(path), repr_lua(cls), long_string(src))
        )
    parts.append("\nlocal REMOTES = { %s }\n" % ", ".join(repr_lua(r) for r in REMOTES))
    parts.append(FOOTER)
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print("wrote %s (%d files, %d KB)" % (OUT, len(FILES), OUT.stat().st_size // 1024))


if __name__ == "__main__":
    main()
