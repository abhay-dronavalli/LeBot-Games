def long_string(text: str) -> str:
    level = 1
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    # Lua drops the newline right after the opening bracket, so the source starts on its first line.
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def main() -> None:
    parts = [HEADER]
    for path, cls, rel in [(p, c, r) for p, c, r in FILES] + OPTIONAL:
        src = (ROBLOX / rel).read_text(encoding="utf-8").replace("\r\n", "\n")
        optional = "true" if (path, cls, rel) in OPTIONAL else "false"
        parts.append(
            "table.insert(SOURCES, { path = %s, class = %s, optional = %s, source = %s })\n"
            % (repr_lua(path), repr_lua(cls), optional, long_string(src))
        )
    parts.append(FOOTER)
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print("wrote %s (%d files, %d KB)" % (OUT, len(FILES) + len(OPTIONAL), OUT.stat().st_size // 1024))


def repr_lua(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
