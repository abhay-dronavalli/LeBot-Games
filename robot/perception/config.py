"""Rig constants for the overhead camera and test objects. Measure, don't guess."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent      # robot/
SHEET_SPEC = ROOT / "assets" / "workspace_sheet.json"


def _sheet_size():
    """The grid sheet's size in mm, read from the spec so exactly one file owns it.

    This used to be `215.9, 279.4` written out in four modules. That was fine while the sheet
    was always portrait US Letter, but it silently breaks the moment the sheet changes: the
    perception ROI is built from these numbers and `segment.py` rejects any detection whose
    centre falls outside them, so a landscape sheet would lose its right-hand 64 mm with no
    error anywhere. Generated by `robot/scripts/make_sheet.py`.
    """
    import json
    try:
        s = json.loads(SHEET_SPEC.read_text())["sheet"]
        return float(s["w_mm"]), float(s["h_mm"])
    except (OSError, KeyError, ValueError, TypeError):
        return 215.9, 279.4            # the original portrait US Letter sheet


SHEET_W_MM, SHEET_H_MM = _sheet_size()

