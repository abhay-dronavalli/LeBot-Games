# The block colours this kit actually has. Guesses only choose from these. The order is also
# colour calibration's default spot order (A1, A3, B2, C1, C2, C3). Six blocks on a 3x3 grid
# can't all avoid neighbours, so the only neighbours (row C, and B2 above C2) are dissimilar
# colours: similar colours that touch merge and can't be split (teal + light blue at 17:24).
BLOCK_COLORS = ["orange", "yellow", "purple", "teal", "red", "light blue"]

# The colours blocks may be named, out of BLOCK_COLORS. This used to hold only one of each
# confusable pair, because raw hue alone could not split them in this room's glare - orange and
# yellow landed on the same hue, and teal and light blue within 6 degrees. Calibrating by
# position fixed that: the memory learns each block's own signature (hue, chroma and lightness)
# rather than guessing from hue, and the six measured on this rig separate cleanly -
#
#   red 40.6  orange 60.9  yellow 84.4  teal 184.8  light blue 253.3  purple 321.3 (hue)
#
# with orange and yellow also 16 points apart in L. Re-run color_calibrate after any lighting
# change; if two colours start swapping, that is the signal to narrow this list again.
ACTIVE_COLORS = list(BLOCK_COLORS)
